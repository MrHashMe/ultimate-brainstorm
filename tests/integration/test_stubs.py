    def test_tournament_verdicts_are_order_consistent(self):
        cards = {"I-001": "Title: Alpha board\nProblem: one", "I-002": "Title: Beta queue\nProblem: two",
                 "I-003": "Title: Gamma loop\nProblem: three"}

        def prompt(order):
            labels = dict(zip(order, "ABC"))
            body = ["HEADER", "", "CARDS"]
            for k in order:
                body += ["", "[Card %s]" % labels[k]] + cards[k].split("\n")
            body += ["", "PAIRS (the first card named in a pair is FIRST, the second is SECOND)"]
            pairs = [("I-001", "I-002"), ("I-001", "I-003"), ("I-002", "I-003")]
            mapping = {}
            for n, (x, y) in enumerate(pairs, 1):
                pid = "P%02d" % n
                body.append("%s: Card %s vs Card %s" % (pid, labels[x], labels[y]))
                mapping[pid] = (x, y)
            return "\n".join(body), mapping

        c = {"type": "json", "schema": schema("verdicts"),
             "cover": {"array": "verdicts", "key": "pair_id", "ids": ["P01", "P02", "P03"]}}
        winners = []
        for order in (["I-001", "I-002", "I-003"], ["I-003", "I-001", "I-002"]):
            text, mapping = prompt(order)
            out = json.loads(stubs.respond(make_job("TOURNAMENT", "judge", c, jid="j-" + order[0]), text))
            won = {}
            for v in out["verdicts"]:
                x, y = mapping[v["pair_id"]]
                won[frozenset((x, y))] = x if v["winner"] == "FIRST" else y
            winners.append(won)
        self.assertEqual(winners[0], winners[1])
        rev_text, rev_map = prompt(["I-001", "I-002", "I-003"])
        rev_text = re.sub(r"Card ([A-C]) vs Card ([A-C])", r"Card \2 vs Card \1", rev_text)
        out = json.loads(stubs.respond(make_job("TOURNAMENT", "judge", c, jid="j-rev"), rev_text))
        for v in out["verdicts"]:
            x, y = rev_map[v["pair_id"]]
            winner = y if v["winner"] == "FIRST" else x
            self.assertEqual(winner, winners[0][frozenset((x, y))])

