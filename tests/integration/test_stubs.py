def make_job(template, kind, contract, facts=None, jid=None, run=None):
    job = {"schema": 1, "run": run, "id": jid or ("t-" + template), "step": "x", "kind": kind,
           "template": template, "family": "claude", "tier": "default", "prompt_file": "prompts/x.prompt.md",
           "out": "out.md", "tools": "none", "cwd": "empty", "contract": contract, "privacy": {}}
    if facts is not None:
        job["stub"] = facts
    return job


def outside_fences(text):
    out, inside = [], False
    for line in text.split("\n"):
        if line.strip().startswith("```"):
            inside = not inside
            continue
        if not inside:
            out.append(line)
    return "\n".join(out)


