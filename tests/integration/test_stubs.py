class StubSemanticsTests(unittest.TestCase):
    def curator(self, aliases, homogenized=False):
        c = {"type": "json", "schema": schema("merges")}
        job = make_job("CURATOR", "curator", c, {"aliases": aliases, "axes": AXES})
        old = os.environ.get("UB_STUB_HOMOGENIZED")
        try:
            if homogenized:
                os.environ["UB_STUB_HOMOGENIZED"] = "1"
            else:
                os.environ.pop("UB_STUB_HOMOGENIZED", None)
            return json.loads(stubs.respond(job, ""))
        finally:
            if old is None:
                os.environ.pop("UB_STUB_HOMOGENIZED", None)
            else:
                os.environ["UB_STUB_HOMOGENIZED"] = old

    def test_curator_shape(self):
        aliases = ["S%d-%02d" % (s, i) for s in range(1, 6) for i in range(1, 13)] + ["HP-01", "H-01", "H-02"]
        data = self.curator(aliases)
        ideas = data["ideas"]
        seen = [a for i in ideas for a in i["aliases"]]
        self.assertEqual(sorted(seen), sorted(aliases), "every alias maps to exactly one canonical idea")
        self.assertTrue(all(1 <= len(i["aliases"]) <= 3 for i in ideas))
        self.assertTrue(all(len(i["aliases"]) == 3 for i in ideas[:-1]))
        clusters = [i["cluster"] for i in ideas]
        self.assertTrue(6 <= len(set(clusters)) <= 12, set(clusters))
        largest = max(clusters.count(c) for c in set(clusters))
        self.assertLessEqual(largest / float(len(ideas)), 0.25)
        prim = [i for i in ideas if i["primary"]]
        self.assertEqual(len(prim), 1)
        self.assertIn("HP-01", prim[0]["aliases"])
        cells = set(tuple(i["cell"]) for i in ideas)
        self.assertGreater(len(cells), 3, "cells cycle over the axes")
        self.assertEqual(len(set(i["key"] for i in ideas)), len(ideas))
        for i in ideas:
            for field in ("title", "pitch", "mechanism", "cluster"):
                self.assertIsNone(ALIAS_RX.search(i[field]), i[field])
                self.assertIsNone(LABEL_WORDS.search(i[field]), i[field])

    def test_curator_homogenized(self):
        aliases = ["S%d-%02d" % (s, i) for s in range(1, 6) for i in range(1, 13)]
        data = self.curator(aliases, homogenized=True)
        clusters = [i["cluster"] for i in data["ideas"]]
        largest = max(clusters.count(c) for c in set(clusters))
        self.assertGreater(largest / float(len(clusters)), 0.25)

