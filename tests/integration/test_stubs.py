class StubEnvTests(unittest.TestCase):
    def setUp(self):
        self._saved = {k: os.environ.get(k) for k in ("UB_STUB_FAIL", "UB_STUB_DELAY_S")}

    def tearDown(self):
        for k, v in self._saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v

    def test_fail_regex(self):
        os.environ["UB_STUB_FAIL"] = r"^4\.2-S3$"
        with self.assertRaises(stubs.StubFailure):
            stubs.respond({"id": "4.2-S3", "contract": {"type": "text"}}, "")
        stubs.respond({"id": "4.2-S2", "contract": {"type": "text"}}, "")

    def test_delay(self):
        os.environ["UB_STUB_DELAY_S"] = "0.3"
        t0 = time.time()
        stubs.respond({"id": "d", "contract": {"type": "text"}}, "")
        self.assertGreaterEqual(time.time() - t0, 0.25)

    def test_regex_example_generator(self):
        for rx in (r"^RESULT: PENDING$", CHECK_FINAL, REVIEW_FINAL, r"\d{3}-[a-z]+", r"[^x]y{2,3}(z|w)?$",
                   r"^(?:A|B)\s+\w+\.$"):
            ex = stubs.regex_example(rx)
            self.assertIsNotNone(ex, rx)
            self.assertRegex(ex, rx)


