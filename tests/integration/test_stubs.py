    def files_of(self, template, contract, facts):
        from ublib import filesproto
        text = stubs.respond(make_job(template, "writer", contract, facts), "")
        files, status, warnings = filesproto.parse_file_blocks(text)
        self.assertEqual(status.get("status"), "complete")
        return files

    def arch_files(self):
        cases = {c[0]: c for c in CASES}
        files = {}
        for name in ("ARCH-PACKAGE-STRUCTURE", "ARCH-PACKAGE-CROSSCUT"):
            _t, _k, contract, facts = cases[name]
            files.update(self.files_of(name, contract, facts))
        return files

    def test_no_placeholders_outside_fences(self):
        for rel, content in self.arch_files().items():
            self.assertIsNone(PLACEHOLDER_RX.search(outside_fences(content)), rel)

    def test_mermaid_lines_balance(self):
        for rel, content in self.arch_files().items():
            blocks = re.findall(r"```mermaid\n(.*?)```", content, re.S)
            for block in blocks:
                lines = [l for l in block.split("\n") if l.strip()]
                self.assertIn(lines[0].strip().split()[0], ("C4Context", "C4Container", "C4Component", "flowchart",
                                                            "graph", "sequenceDiagram", "erDiagram",
                                                            "stateDiagram-v2", "classDiagram"), rel)
                for line in lines:
                    self.assertNotIn("\t", line)
                    for o, c in ("()", "[]", "{}"):
                        self.assertEqual(line.count(o), line.count(c), "%s: %r" % (rel, line))
                    self.assertEqual(line.count('"') % 2, 0, "%s: %r" % (rel, line))
            c4 = [i for i, b in enumerate(blocks) if b.strip().startswith("C4")]
            for i in c4:
                self.assertTrue(any(b.strip().startswith(("flowchart", "graph")) for b in blocks[i + 1:]), rel)

