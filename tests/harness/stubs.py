def _final_line(ctx, rx):
    """The final line for a contract regex: stub.final_line, then the known verdict cycles, then a generated match."""
    cands = []
    if ctx.fact("final_line"):
        cands.append(str(ctx.facts["final_line"]))
    text = rx or ""
    if "WHOLE-EFFORT" in text:
        cands.append("WHOLE-EFFORT: CONTINUE - the stub synthesis found no stop condition")
    if "RESULT" in text:
        cands.append("RESULT: PENDING")
    if "VERDICT" in text and ("CROWDED" in text or "LOCATED" in text):
        key = ctx.fact("idea_id", ctx.id)
        verdict = ["NOT LOCATED", "ADJACENT", "CROWDED"][ctx.cycle(3, key)]
        cands.append("VERDICT: %s; DIFFERENTIATOR: a weekly pilot with a manual fallback" % verdict)
    if "VERDICT" in text and "BACK" in text:
        key = ctx.fact("idea_id", ctx.id)
        cands.append(["VERDICT: BACK", "VERDICT: BACK IF the pilot ward keeps using it",
                      "VERDICT: DON'T BACK"][ctx.cycle(3, str(key) + ctx.id)])
    if text:
        example = regex_example(text)
        if example:
            cands.append(example)
    if not text:
        return cands[0] if cands else None
    for cand in cands:
        try:
            if re.search(text, cand):
                return cand
        except re.error:
            return cands[0] if cands else None
    return cands[0] if cands else "stub"


# ---------------------------------------------------------------- JSON generation

def _types(schema):
    t = schema.get("type")
    if isinstance(t, list):
        return [x for x in t if x != "null"] or ["null"]
    if isinstance(t, str):
        return [t]
    if "properties" in schema:
        return ["object"]
    if "items" in schema:
        return ["array"]
    return []


_FALSE_NAMES = re.compile(r"veto|kill|reject|fail|block|stop|skip|provisional|error|excluded|homogen", re.I)


def _gen(schema, ctx, name="", item_key=None, path=""):
    """Generic instance from a schema (4.5 json stub rules)."""
    if not isinstance(schema, dict):
        return "stub"
    if isinstance(schema.get("enum"), list) and schema["enum"]:
        return schema["enum"][0]
    if "const" in schema:
        return schema["const"]
    types = _types(schema)
    t = types[0] if types else "string"
    if t == "object":
        props = schema.get("properties") or {}
        return {p: _gen(sub, ctx, p, item_key, path + "." + p) for p, sub in props.items()}
    if t == "array":
        items = schema.get("items") if isinstance(schema.get("items"), dict) else {"type": "string"}
        n = max(int(schema.get("minItems") or 0), 1)
        if isinstance(schema.get("maxItems"), int):
            n = min(n, schema["maxItems"])
        return [_gen(items, ctx, name, item_key, path + "[]") for _ in range(n)]
    if t == "integer":
        lo, hi = schema.get("minimum"), schema.get("maximum")
        if isinstance(lo, (int, float)) and isinstance(hi, (int, float)):
            return int((lo + hi) // 2)
        if item_key is not None:
            return 2 + _h(item_key, path) % 3
        if isinstance(lo, (int, float)):
            return int(lo)
        return 3
    if t == "number":
        lo, hi = schema.get("minimum"), schema.get("maximum")
        if isinstance(lo, (int, float)) and isinstance(hi, (int, float)):
            return (lo + hi) / 2.0
        if re.search(r"prob|conf|share|pct|ratio", name, re.I):
            return 0.5
        return 3
    if t == "boolean":
        return not bool(_FALSE_NAMES.search(name or ""))
    if t == "null":
        return None
    text = "stub"
    min_len = schema.get("minLength")
    if isinstance(min_len, int) and len(text) < min_len:
        text = (text + " text") * (min_len // 4 + 1)
    max_len = schema.get("maxLength")
    if isinstance(max_len, int):
        text = text[:max_len]
    return text


def _type_ok(value, t):
    if t == "object":
        return isinstance(value, dict)
    if t == "array":
        return isinstance(value, list)
    if t == "string":
        return isinstance(value, str)
    if t == "boolean":
        return isinstance(value, bool)
    if t == "integer":
        return isinstance(value, int) and not isinstance(value, bool)
    if t == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if t == "null":
        return value is None
    return True


def _conform(schema, value, ctx, name="", item_key=None, path=""):
    """Fit a semantic value to a schema: keep what fits, generate what is missing, drop what is not allowed."""
    if not isinstance(schema, dict) or not schema:
        return value
    if isinstance(schema.get("enum"), list) and schema["enum"]:
        return value if value in schema["enum"] else schema["enum"][0]
    types = _types(schema)
    if types and not any(_type_ok(value, t) for t in types):
        if "null" in (schema.get("type") if isinstance(schema.get("type"), list) else []) and value is None:
            return None
        return _gen(schema, ctx, name, item_key, path)
    if isinstance(value, dict) and (not types or "object" in types):
        props = schema.get("properties")
        if not isinstance(props, dict):
            return value
        out = {}
        for p, sub in props.items():
            if p in value:
                out[p] = _conform(sub, value[p], ctx, p, item_key, path + "." + p)
            else:
                out[p] = _gen(sub, ctx, p, item_key, path + "." + p)
        if schema.get("additionalProperties") is not False:
            for k, v in value.items():
                if k not in out:
                    out[k] = v
        return out
    if isinstance(value, list) and (not types or "array" in types):
        items = schema.get("items") if isinstance(schema.get("items"), dict) else None
        out = [_conform(items, v, ctx, name, item_key, path + "[]") if items else v for v in value]
        min_items = schema.get("minItems")
        while isinstance(min_items, int) and len(out) < min_items:
            out.append(_gen(items or {"type": "string"}, ctx, name, item_key, path + "[]"))
        if isinstance(schema.get("maxItems"), int):
            out = out[:schema["maxItems"]]
        return out
    if isinstance(value, str):
        if isinstance(schema.get("maxLength"), int):
            value = value[:schema["maxLength"]]
        if isinstance(schema.get("minLength"), int) and len(value) < schema["minLength"]:
            value = value + " " + "x" * schema["minLength"]
    return value


def _get_path(obj, dotted):
    cur = obj
    for part in [p for p in str(dotted or "").split(".") if p]:
        if isinstance(cur, dict):
            cur = cur.get(part)
        else:
            return None
    return cur


def _sub_schema(schema, dotted):
    cur = schema
    for part in [p for p in str(dotted or "").split(".") if p]:
        if not isinstance(cur, dict):
            return None
        cur = (cur.get("properties") or {}).get(part)
    return cur if isinstance(cur, dict) else None


def _apply_cover(value, cover, schema, ctx):
    if not isinstance(cover, dict):
        return value
    arr_name, key = cover.get("array"), cover.get("key", "id")
    ids = [str(i) for i in (cover.get("ids") or [])]
    if not ids:
        return value
    arr_schema = _sub_schema(schema, arr_name) if schema else None
    item_schema = arr_schema.get("items") if isinstance(arr_schema, dict) and isinstance(arr_schema.get("items"),
                                                                                           dict) else None
    current = _get_path(value, arr_name) if arr_name else value
    current = current if isinstance(current, list) else []
    by_key = {}
    for item in current:
        if isinstance(item, dict) and key in item:
            by_key.setdefault(str(item[key]), item)
    new = []
    for cid in ids:
        item = by_key.get(cid)
        if item is None:
            item = _gen(item_schema, ctx, "", cid) if item_schema else {}
            if not isinstance(item, dict):
                item = {}
        item = dict(item)
        item[key] = cid
        new.append(item)
    # items whose key is not in the cover are dropped: the cover lists every expected ID
    if not arr_name:
        return new
    parts = [p for p in str(arr_name).split(".") if p]
    if not isinstance(value, dict):
        value = {}
    cur = value
    for part in parts[:-1]:
        if not isinstance(cur.get(part), dict):
            cur[part] = {}
        cur = cur[part]
    cur[parts[-1]] = new
    return value


