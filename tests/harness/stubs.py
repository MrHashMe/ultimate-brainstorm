def _h(*parts):
    """Stable non-negative integer hash of the parts."""
    return int(hashlib.sha256("\x1f".join(str(p) for p in parts).encode("utf-8")).hexdigest()[:12], 16)


class _Ctx(object):
    def __init__(self, job, prompt_text):
        self.job = job if isinstance(job, dict) else {}
        self.prompt = prompt_text or ""
        self.id = str(self.job.get("id") or "stub")
        self.rng = random.Random(int(hashlib.sha256(self.id.encode("utf-8")).hexdigest(), 16))
        facts = self.job.get("stub")
        self.facts = facts if isinstance(facts, dict) else {}
        self.template = str(self.job.get("template") or "").strip().upper()
        if self.template.endswith(".MD"):
            self.template = self.template[:-3]
        self.kind = str(self.job.get("kind") or "").strip().lower()
        run = self.job.get("run")
        self.run_dir = run if isinstance(run, str) and run else None
        split = self.job.get("split")
        self.split = split if isinstance(split, dict) else {}
        self._run_json = None
        self._counter = 0

    # --- prose
    def sentence(self, salt=""):
        self._counter += 1
        k = _h(self.id, salt, self._counter)
        return "%s %s %s %s." % (_SUBJECTS[k % len(_SUBJECTS)], _VERBS[(k // 7) % len(_VERBS)],
                                 _OBJECTS[(k // 53) % len(_OBJECTS)], _TAILS[(k // 401) % len(_TAILS)])

    def sentences(self, n, salt=""):
        return " ".join(self.sentence(salt) for _ in range(max(1, n)))

    def title(self, salt=""):
        k = _h(self.id, "title", salt)
        return "%s %s %s" % (_ADJ[k % len(_ADJ)], _NOUNS[(k // 19) % len(_NOUNS)], _TAGS[(k // 347) % len(_TAGS)])

    def cycle(self, n, key=None):
        return _h(key if key is not None else self.id, "cycle") % n

    # --- run files (read-only fallbacks)
    def run_file(self, *rel):
        if not self.run_dir:
            return None
        return os.path.join(self.run_dir, *rel)

    def run_json_file(self, *rel):
        path = self.run_file(*rel)
        if not path or not os.path.isfile(path):
            return None
        try:
            return textio.read_json(path)
        except (OSError, ValueError):
            return None

    def run_meta(self):
        if self._run_json is None:
            self._run_json = self.run_json_file("run.json") or {}
        return self._run_json

    def fact(self, name, default=None):
        value = self.facts.get(name)
        return default if value in (None, "", [], {}) else value


def _slug(text):
    return re.sub(r"[^a-z0-9]+", "-", str(text).lower()).strip("-") or "item"


# ---------------------------------------------------------------- regex example generator

def _cat_char(cat):
    name = str(cat)
    if "NOT_DIGIT" in name:
        return "a"
    if "DIGIT" in name:
        return "1"
    if "NOT_SPACE" in name:
        return "a"
    if "SPACE" in name:
        return " "
    if "NOT_WORD" in name:
        return " "
    if "WORD" in name:
        return "a"
    return "a"


def _in_char(items):
    if items and items[0][0] == _sre_c.NEGATE:
        body = items[1:]
        for cand in "ax1 Z_-.":
            if not _in_set(cand, body):
                return cand
        return "~"
    for op, av in items:
        if op == _sre_c.LITERAL:
            return chr(av)
        if op == _sre_c.RANGE:
            return chr(av[0])
        if op == _sre_c.CATEGORY:
            return _cat_char(av)
    return "a"


def _in_set(ch, items):
    for op, av in items:
        if op == _sre_c.LITERAL and ord(ch) == av:
            return True
        if op == _sre_c.RANGE and av[0] <= ord(ch) <= av[1]:
            return True
        if op == _sre_c.CATEGORY:
            probe = {"1": "DIGIT", " ": "SPACE"}.get(ch, "WORD" if (ch.isalnum() or ch == "_") else "")
            name = str(av)
            if probe and probe in name and "NOT_" not in name:
                return True
    return False


_REPEATS = tuple(getattr(_sre_c, n) for n in ("MAX_REPEAT", "MIN_REPEAT", "POSSESSIVE_REPEAT") if hasattr(_sre_c, n))


def _emit(items, out):
    for op, av in items:
        if op == _sre_c.LITERAL:
            out.append(chr(av))
        elif op == _sre_c.NOT_LITERAL:
            out.append("x" if av != ord("x") else "y")
        elif op == _sre_c.ANY:
            out.append("x")
        elif op == _sre_c.IN:
            out.append(_in_char(av))
        elif op == _sre_c.BRANCH:
            _emit(av[1][0], out)
        elif op == _sre_c.SUBPATTERN:
            _emit(av[-1], out)
        elif op in _REPEATS:
            lo, _hi, sub = av
            sub = list(sub)
            if lo >= 1 and len(sub) == 1 and sub[0][0] == _sre_c.ANY:
                out.append("stub text")
                continue
            for _ in range(lo):
                _emit(sub, out)
        elif op == _sre_c.CATEGORY:
            out.append(_cat_char(av))
        # AT (anchors), ASSERT, ASSERT_NOT, GROUPREF and others emit nothing


def regex_example(pattern):
    """A string that re.search(pattern, ...) matches, or None when the generator cannot build one."""
    try:
        parsed = _sre_parse.parse(pattern)
        out = []
        _emit(list(parsed), out)
        text = "".join(out)
        if re.search(pattern, text):
            return text
    except Exception:  # noqa: BLE001 - any parser surprise means "no example"
        return None
    return None


