def _quick_aliases(ctx, n):
    """Source IDs for n quick ideas, one to three each (as _merges merges the CURATOR's): the job's stub facts (the
    QA-, QB- and H- IDs of the pool and seeds) grouped by prefix and taken three at a time from each group in turn, so
    ideas come from both generators and from the human seeds; a pool too small for n ideas is reused one ID at a
    time. Without facts: QA-01, QA-02, ... (bs.py quick-pick derives each idea's origin from these)."""
    flat = [str(a) for a in (ctx.fact("aliases") or [])]
    if not flat:
        return [["QA-%02d" % (i + 1)] for i in range(n)]
    groups = {}
    for a in flat:
        groups.setdefault(re.sub(r"-\d+$", "", a), []).append(a)
    queues = list(groups.values())
    out, turn = [], 0
    while len(out) < n and any(queues):
        queue = queues[turn % len(queues)]
        turn += 1
        if queue:
            out.append(queue[:3])
            del queue[:3]
    while len(out) < n:
        out.append([flat[len(out) % len(flat)]])
    return out


