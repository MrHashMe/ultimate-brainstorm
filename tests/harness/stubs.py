def _mermaid(kind, conts, exts=()):
    lines = ["```mermaid"]
    if kind == "C4Container":
        lines.append("C4Container")
        lines.append("  title Containers of the shift swap service")
        lines.append("  Person(nurse, \"Nurse\", \"Requests swaps\")")
        for cid, name, tech in conts:
            lines.append("  Container(%s, \"%s\", \"%s\", \"%s\")" % (_slug(cid).replace("-", ""), name, tech, cid))
        for e in exts:
            lines.append("  System_Ext(%s, \"%s\", \"external system\")" % (_slug(e).replace("-", ""), e))
    elif kind == "flowchart":
        lines.append("flowchart LR")
        prev = "nurse"
        lines.append("  nurse[\"Nurse\"]")
        for cid, name, _tech in conts:
            node = _slug(cid).replace("-", "")
            lines.append("  %s[\"%s %s\"]" % (node, cid, name))
            lines.append("  %s --> %s" % (prev, node))
            prev = node
        for e in exts:
            node = _slug(e).replace("-", "")
            lines.append("  %s[\"%s\"]" % (node, e))
            lines.append("  %s --> %s" % (prev, node))
    elif kind == "sequenceDiagram":
        lines.append("sequenceDiagram")
        names = [_slug(c[0]).replace("-", "") for c in conts] or ["api"]
        lines.append("  participant nurse as Nurse")
        for node in names[:3]:
            lines.append("  participant %s" % node)
        lines.append("  nurse->>%s: request" % names[0])
        if len(names) > 1:
            lines.append("  %s->>%s: store" % (names[0], names[1]))
            lines.append("  %s-->>%s: stored" % (names[1], names[0]))
        lines.append("  %s-->>nurse: confirmed" % names[0])
    elif kind == "erDiagram":
        lines.append("erDiagram")
        lines.append("  NURSE ||--|| SWAP_REQUEST : creates")
        lines.append("  SHIFT |o--|| SWAP_REQUEST : covers")
    else:
        lines.append(kind)
        lines.append("  a --> b")
    lines.append("```")
    return "\n".join(lines)


def _table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


