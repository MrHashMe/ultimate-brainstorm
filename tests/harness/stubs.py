def _maybe_fail(job_id):
    rx = os.environ.get("UB_STUB_FAIL", "")
    if rx:
        try:
            hit = re.search(rx, job_id)
        except re.error:
            hit = rx == job_id
        if hit:
            raise StubFailure("UB_STUB_FAIL matched job %s" % job_id)


def _maybe_delay():
    raw = os.environ.get("UB_STUB_DELAY_S", "")
    try:
        delay = float(raw) if raw else 0.0
    except ValueError:
        delay = 0.0
    if delay > 0:
        time.sleep(min(delay, 3600.0))


def respond(job, prompt_text):
    """Return raw model-like output text that satisfies job["contract"] (and FILE protocol + STATUS for "files").

    Deterministic: seeded by job["id"]. Reads optional job["stub"] facts. Honors UB_STUB_FAIL (raise StubFailure for
    matching job ids), UB_STUB_DELAY_S (sleep), UB_STUB_HOMOGENIZED (curator puts > 25% of ideas in one cluster)."""
    ctx = _Ctx(job, prompt_text)
    _maybe_fail(ctx.id)
    _maybe_delay()
    contract = ctx.job.get("contract") if isinstance(ctx.job.get("contract"), dict) else {"type": "text"}
    gen = _GENERATORS.get(str(contract.get("type") or "text"), _gen_text)
    return gen(ctx, contract)
