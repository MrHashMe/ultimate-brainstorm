def _ensure_rules(content, rules):
    if not isinstance(rules, dict):
        return content
    for h in rules.get("headings") or []:
        line = _heading_line(h)
        if not re.search(r"(?im)^" + re.escape(line.strip()), content):
            content = content.rstrip() + "\n\n" + line + "\n\nAdded to satisfy the required outline.\n"
    for kind in rules.get("mermaid") or []:
        if not re.search(r"```mermaid\s*\n\s*" + re.escape(str(kind)) + r"\b", content):
            content = content.rstrip() + "\n\n```mermaid\n%s\n  a --> b\n```\n" % kind \
                if str(kind) in ("flowchart", "graph") else \
                content.rstrip() + "\n\n```mermaid\n%s\n```\n" % kind
    return content


def _glob_name(pattern):
    name = str(pattern).replace("**/", "").replace("**", "stub")
    name = name.replace("*", "stub").replace("?", "x")
    if not re.search(r"\.(md|ya?ml|json|mmd)$", name):
        name = name.rstrip("/") + "/stub.md"
    return name.lstrip("/")


def _gen_files(ctx, c):
    required = [str(r) for r in (c.get("required") or [])]
    allowed = [str(a) for a in (c.get("allowed") or [])]
    per_file = c.get("per_file") if isinstance(c.get("per_file"), dict) else {}
    names = list(required)
    if not names:
        literal = [a for a in allowed if not re.search(r"[*?\[]", a)]
        names = literal[:1] or ([_glob_name(allowed[0])] if allowed else ["stub.md"])
    out = []
    for rel in names:
        content = _ensure_rules(_file_content(ctx, rel), per_file.get(rel))
        out.append("=== FILE: %s ===" % rel)
        out.append(content.rstrip("\n"))
        out.append("=== END FILE ===")
    status = {"status": "complete", "assumptions": ["Stub output: every fact is an assumption."],
              "open_questions": [], "reason": ""}
    out.append("=== STATUS ===")
    out.append(json.dumps(status, ensure_ascii=True))
    out.append("=== END STATUS ===")
    return "\n".join(out) + "\n"


