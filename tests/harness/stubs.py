def _parse_tournament_prompt(prompt):
    """({label: card text}, {pair_id: (first_label, second_label)}) from a bs.py tournament prompt."""
    cards, pairs, cur, buf = {}, {}, None, []
    for line in prompt.replace("\r\n", "\n").split("\n"):
        m = re.match(r"^\[Card ([A-Z]{1,2})\]\s*$", line.strip())
        if m:
            if cur is not None:
                cards[cur] = "\n".join(buf).strip()
            cur, buf = m.group(1), []
            continue
        pm = re.match(r"^\s*(P\d+)\s*:\s*Card\s+([A-Z]{1,2})\s+vs\.?\s+Card\s+([A-Z]{1,2})\b", line)
        if pm:
            pairs[pm.group(1)] = (pm.group(2), pm.group(3))
            if cur is not None:
                cards[cur] = "\n".join(buf).strip()
                cur = None
            continue
        if cur is not None:
            if line.strip().upper().startswith("PAIRS"):
                cards[cur] = "\n".join(buf).strip()
                cur = None
            else:
                buf.append(line)
    if cur is not None:
        cards[cur] = "\n".join(buf).strip()
    return cards, pairs


def _verdicts(ctx, cover_ids):
    cards, pairs = _parse_tournament_prompt(ctx.prompt)
    ids = list(cover_ids or sorted(pairs) or ["P01"])
    out = []
    for pid in ids:
        winner = "FIRST"
        if pid in pairs:
            a, b = pairs[pid]
            ha = hashlib.sha256(cards.get(a, a).encode("utf-8")).hexdigest()
            hb = hashlib.sha256(cards.get(b, b).encode("utf-8")).hexdigest()
            winner = "FIRST" if ha <= hb else "SECOND"  # decided by content, so both orders agree
        out.append({"pair_id": pid, "winner": winner})
    return {"verdicts": out}


def _shape_of(ctx, contract, schema):
    if ctx.template in _TEMPLATE_SHAPES:
        return _TEMPLATE_SHAPES[ctx.template]
    sid = str((schema or {}).get("$id") or "").strip().lower()
    if sid.endswith(".schema.json"):
        sid = sid[:-len(".schema.json")]
    if sid in _KNOWN_SHAPES:
        return sid
    ref = contract.get("schema")
    if isinstance(ref, str):
        stem = os.path.basename(ref.replace("\\", "/")).lower()
        for suffix in (".schema.json", ".json"):
            if stem.endswith(suffix):
                stem = stem[:-len(suffix)]
                break
        if stem in _KNOWN_SHAPES:
            return stem
    cover = contract.get("cover") if isinstance(contract.get("cover"), dict) else {}
    arr = str(cover.get("array") or "")
    props = (schema or {}).get("properties") or {}
    if arr == "verdicts" or "verdicts" in props:
        return "verdicts"
    if arr == "scores" or ("scores" in props and ctx.kind == "judge"):
        return "screen"
    if ctx.kind == "curator":
        return "merges"
    return None


