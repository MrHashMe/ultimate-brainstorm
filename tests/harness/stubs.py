def _long_md(ctx, title, headings, salt, words=150, extra=""):
    parts = ["# " + title, ""]
    for n, h in enumerate(headings):
        parts.append(h)
        parts.append("")
        parts.append(ctx.sentences(2, "%s%d" % (salt, n)))
        parts.append("")
    if extra:
        parts.append(extra)
        parts.append("")
    text = "\n".join(parts)
    # count words the way lints.word_count does (tokens with a word character; table pipes and heading marks
    # are not words), with a small margin, so stub packages pass the 120-word rule (A7)
    count = len([w for w in text.split() if re.search(r"\w", w)])
    if count < words:
        text += "\n" + _words_to("", words - count, ctx, salt).strip() + "\n"
    return text.rstrip() + "\n"


