class GateCorpusU(tl.EngineTestCase):
    variant = "product"
    make_ctx = s.GateCorpusS.make_ctx  # the Q fixtures on the row's variant
    read = s.GateCorpusS.read

    def check(self, gate):
        with mock.patch("os.fsync", lambda fd: None):  # a run per row, in a temp dir: no need to reach the disk
            for n, row in enumerate(ROWS[gate]):
                reply, intent, opts = row[0], row[1], row[2] if len(row) > 2 else {}
                k = (gate, _key(reply, opts))
                with self.subTest(gate=gate, reply=reply, opts=opts):
                    got = self.read(gate, reply, n, opts)
                    if k in ASKED:
                        self.assertEqual(got["r"], "ask", "pinned as asked again, got %r" % (got,))
                    else:
                        want = RESIDUAL.get(k, intent)
                        self.assertTrue(q.matches(want, got), "want %s, got %r" % (want, got))

    def test_pinned_rows_are_rows(self):
        keys = set((g, _key(r[0], r[2] if len(r) > 2 else None)) for g in ROWS for r in ROWS[g])
        self.assertEqual((ASKED | set(RESIDUAL)) - keys, frozenset())


def _add(gate):
    setattr(GateCorpusU, "test_%s" % gate.lower(), lambda self: self.check(gate))


for _gate in ROWS:
    _add(_gate)


