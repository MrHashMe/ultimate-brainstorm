class GateCorpusW(tl.EngineTestCase):
    variant = "product"
    make_ctx = s.GateCorpusS.make_ctx  # the Q fixtures on the product variant

    def read(self, gate, reply, n):
        provided = {"reply": reply}
        if gate == "G0v1":
            got = q.read_v1(self, "2026-09-28-w%d" % n, provided)
            return dict(got, how="rb" if got.get("rb") else "ask" if got["r"] == "ask" else "act")
        gid = "G0" if gate == "G0k" else gate
        ctx = q.GateCorpusQ.build(self, gate, n)
        if gate == "G4":
            ctx.write("screen/ideas.md", "".join("I-%03d | idea %d | pitch | mechanism\n" % (i, i)
                                                 for i in range(1, 31)))
        ans, _notes, errs = gates.prepare_answer(ctx, gid, provided)
        if errs:
            return {"r": "ask", "how": "ask", "why": errs[0]}
        rb = gates.read_back(ctx, gid, provided, ans)
        with mock.patch.object(gates.registry, "render_shortlist", lambda *a, **k: None):
            effects = gates.apply(ctx, gid, ans) if gate not in ("G9", "G13") else []
        return dict(s.outcome(gate, ctx, ans, effects), how="rb" if rb else "act")

    def check(self, gate):
        with mock.patch("os.fsync", lambda fd: None):  # a run per row, in a temp dir: no need to reach the disk
            for n, (reply, intent, how) in enumerate(ROWS[gate]):
                with self.subTest(gate=gate, reply=reply):
                    got = self.read(gate, reply, n)
                    if how == "ask":
                        self.assertEqual(got["r"], "ask", "pinned as asked again, got %r" % (got,))
                    else:
                        want = RESIDUAL.get((gate, _key(reply)), intent)
                        self.assertEqual(got["how"], how, "want %s %s, got %r" % (how, want, got))
                        self.assertTrue(q.matches(want, got), "want %s %s, got %r" % (how, want, got))

    def test_pinned_rows_are_rows(self):
        keys = set((g, _key(r[0])) for g in ROWS for r in ROWS[g])
        self.assertEqual(set(RESIDUAL) - keys, set())
        self.assertEqual(set(r[2] for g in ROWS for r in ROWS[g]) - {"act", "rb", "ask"}, set())


def _add(gate):
    setattr(GateCorpusW, "test_%s" % gate.lower(), lambda self: self.check(gate))


for _gate in ROWS:
    _add(_gate)


class Floods(unittest.TestCase):
    """The patterns of the Phase X fixes stay linear (test_t_ta_gate_corpus_s.Floods)."""

    def test_linear(self):
        n = 20000
        floods = (
            ("G0", "don't start " + "yet " * n), ("G0", "never start until " + "x " * n), ("G0", "gooo" * n),
            ("G0", "fo " * n), ("G1", "did it " * n), ("G5", "kill both. keep both. " * n), ("G5", "not keep " * n),
            ("G11", "I pick " * n), ("G11", "Letter: " * n), ("G14", "both of them " * n),
            ("G2f", "get back to u " * n), ("G9", "didnt pass " * n), ("GX", "the STOP was " * n),
            ("GX", "said continue " * n), ("G1", "wait not yet " * n))
        for gid, text in floods:
            t0 = time.perf_counter()
            gates.parse_reply(gid, text, None, [])
            if gid == "G0":
                gates.parse_kickoff(text, [])
            self.assertLess(time.perf_counter() - t0, 10.0, (gid, text[:24]))


