class Schemas(unittest.TestCase):
    def load(self, name):
        with open(os.path.join(TPL, "schemas", name + ".schema.json"), encoding="utf-8") as f:
            return json.load(f)

    def walk(self, node, path, root=False):
        allowed = SCHEMA_KEYWORDS | ({"$id"} if root else set())
        self.assertTrue(set(node) <= allowed, "%s: keywords %s" % (path, sorted(set(node) - allowed)))
        if node.get("type") == "object":
            self.assertIs(node.get("additionalProperties"), False, path)
            self.assertEqual(sorted(node.get("required", [])), sorted(node.get("properties", {})), path)
            self.assertTrue(node.get("properties"), path)
            for k, v in node["properties"].items():
                self.walk(v, path + "." + k)
        elif node.get("type") == "array":
            self.walk(node["items"], path + "[]")
        else:
            self.assertIn(node.get("type"), ("string", "number", "integer", "boolean"), path)

