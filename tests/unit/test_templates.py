class Choices(unittest.TestCase):
    def table(self, name):
        text = read(os.path.join(TPL, "prompts", name + ".md"))
        blocks = CHOICES_RX.findall(text)
        self.assertEqual(len(blocks), 1, name)
        ph, key, rows = blocks[0]
        table = {}
        for r in rows.split("\n"):
            k, v = r.split(" | ", 1)
            table[k] = v
        self.assertIn("{{%s}}" % ph, COMMENT_RX.sub("", text), name)
        return key, table

    def test_archetypes(self):
        key, t = self.table("ARCH-CANDIDATE")
        self.assertEqual(key, "ARCHETYPE_ID")
        self.assertEqual(set(t), {"A", "B-local-first", "B-buy", "B-event", "C", "D", "A-software", "B-software"})
        self.assertTrue(t["A"].startswith("Boring by default: a modular monolith on managed services"))
        self.assertIn("{{OTHER_ARCHETYPES}}", t["C"])
        self.assertEqual(t["A-software"], "Smallest change to the current architecture (cite files).")
        self.assertEqual(t["B-software"], "One new bounded component or service.")
        self.assertTrue(t["D"].startswith("Cost-minimal"))

    def test_lenses(self):
        key, t = self.table("LENS")
        self.assertEqual((key, sorted(t)), ("STRATEGY_ID", ["L1", "L2", "L3", "L4", "L5", "L6"]))
        key, t = self.table("ARCH-REVIEW")
        self.assertEqual((key, sorted(t)), ("REVIEW_LENS", ["L1", "L2", "L3", "L4"]))

    def test_render_picks_choice_and_strips_comments(self):
        text = read(os.path.join(TPL, "prompts", "ARCH-CANDIDATE.md"))
        out = render(text, {"ARCHETYPE_ID": "C", "OTHER_ARCHETYPES": "A (boring), B (event-driven)"}, prompt=True)
        self.assertTrue(out.startswith(GUARD))
        self.assertNotIn("<!--", out)
        self.assertIn("The others are: A (boring), B (event-driven).", out)
        self.assertNotIn("{{", out)


