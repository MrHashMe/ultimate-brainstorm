class Contracts(unittest.TestCase):
    """Each manifest contract is coherent with its template and accepts a well-formed synthetic output."""

    def setUp(self):
        self.m = load_manifest()
        self.run = tempfile.mkdtemp(prefix="ub-tpl-")

    def tearDown(self):
        shutil.rmtree(self.run, ignore_errors=True)

    def tpl(self, name):
        return read(os.path.join(TPL, "prompts", name + ".md"))

    def synth_files(self, c):
        per = c.get("per_file") or {}
        parts = []
        for rel in c.get("required") or []:
            if rel == "decisions.json":  # a register: validated against its kit schema (validate.REGISTER_SCHEMAS)
                with open(os.path.join(TPL, "schemas", "arch-decisions.schema.json"), encoding="utf-8") as f:
                    body = json.dumps(instance(json.load(f)))
            elif rel.endswith(".json"):
                body = '{"Value": 60, "Feasibility": 40}'
            else:
                rules = per.get(rel, {})
                chunks = ["# Doc"]
                for h in rules.get("headings", []):
                    chunks.append("%s stub title\nSome text." % h if not h.endswith(":") else "%s stub" % h)
                for mt in rules.get("mermaid", []):
                    chunks.append("```mermaid\n%s\n  A[One] --> B[Two]\n```" % mt)
                body = "\n\n".join(chunks)
            parts.append("=== FILE: %s ===\n%s\n=== END FILE ===" % (rel, body))
        if c.get("status_trailer"):
            parts.append('=== STATUS ===\n{"status":"complete","assumptions":[],"open_questions":[],"reason":""}\n'
                         "=== END STATUS ===")
        return "\n".join(parts) + "\n"

    def synth(self, name, info):
        c = dict(info["contract"])
        t = c["type"]
        if t == "text":
            samples = {"PING": "PONG", "GAP": "TENSION: the cell mixes two exclusive audiences",
                       "PRECOMMIT": "I-001: BACK - clear pain", "REBUTTAL": "Item 1: HOLD - the check cites data"}
            return c, samples[name]
        if t == "idea-blocks":
            prefix = c["prefix"].replace("{{STRATEGY_ID}}", "S3")
            c["prefix"] = prefix
            blocks = ["### %s-%02d Idea %d\n- Pitch: p\n- Mechanism: m\n- Fails if: f" % (prefix, i, i)
                      for i in range(1, c["min"] + 1)]
            return c, "\n\n".join(blocks)
        if t == "json":
            if not c["schema"].startswith("SK:"):
                return None, None  # run-relative schema written by bs.py schemas
            with open(os.path.join(_SK, c["schema"][3:]), encoding="utf-8") as f:
                obj = instance(json.load(f))
            if c.get("cover"):
                c["cover"] = dict(c["cover"], ids=["stub"])
            return c, json.dumps(obj)
        if t == "sections":
            parts = ["%s\nText." % h for h in c["headings"]]
            if c.get("json_tail"):
                with open(os.path.join(_SK, c["json_tail"][3:]), encoding="utf-8") as f:
                    parts.append("```json\n%s\n```" % json.dumps(instance(json.load(f))))
            if c.get("final_line"):
                parts.append(info["final_example"])
            return c, "\n\n".join(parts)
        if t == "cards":
            c["ids"] = ["I-001", "I-002"]
            cards = ["## %s\n%s" % (cid, "\n".join("%s value" % p for p in c["lines"])) for cid in c["ids"]]
            return c, "\n\n".join(cards)
        if t == "files":
            return c, self.synth_files(c)
        self.fail("unknown contract type %s" % t)

    def test_synthetic_outputs_validate(self):
        checked = 0
        for name, info in self.m["prompts"].items():
            if info["contract"] is None:
                self.assertEqual(name, "GEN-HEADER")
                continue
            c, text = self.synth(name, info)
            if c is None:
                continue
            ok, errors, _ = check_contract(text, c, self.run)
            self.assertTrue(ok, "%s: %s" % (name, errors))
            checked += 1
        self.assertGreaterEqual(checked, 45)

    def test_contract_headings_and_files_are_named_in_templates(self):
        for name, info in self.m["prompts"].items():
            c = info["contract"] or {}
            text = self.tpl(name)
            for h in c.get("headings", []):
                self.assertIn(h, text, "%s: heading %s not in template" % (name, h))
            if c.get("final_line"):
                ex = info["final_example"]
                self.assertRegex(ex, c["final_line"])
                self.assertIn(ex.split(":")[0] + ":", text, name)
            if c.get("type") == "files":
                self.assertIn("{{ALLOWED_FILES}}", text, name)
                self.assertIn("split_root", info, name)
                for rel in c.get("required", []):
                    self.assertIn(rel.split("/")[-1], text, "%s: %s not named" % (name, rel))
                for rel, rules in (c.get("per_file") or {}).items():
                    for h in rules.get("headings", []):
                        self.assertIn(h, text, "%s: %s heading %s" % (name, rel, h))
                    for mt in rules.get("mermaid", []):
                        self.assertIn(mt, text, "%s: %s mermaid %s" % (name, rel, mt))
                if c.get("status_trailer"):
                    self.assertIn("=== STATUS ===", text, name)
            if c.get("type") == "json" and c["schema"].startswith("SK:"):
                self.assertTrue(os.path.isfile(os.path.join(_SK, c["schema"][3:])), name)

    def test_frame_headings_everywhere(self):
        for name in ("FRAME-FINAL", "FRAME-DRAFT"):
            text = self.tpl(name)
            for h in self.m["frame_headings"]:
                self.assertIn(h, text, name)
