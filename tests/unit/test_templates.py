class SkillMd(unittest.TestCase):
    def setUp(self):
        self.text = read(os.path.join(_SK, "SKILL.md"))

    def frontmatter(self):
        self.assertTrue(self.text.startswith("---\n"))
        end = self.text.index("\n---\n", 4)
        fm = {}
        cur = None
        for ln in self.text[4:end].split("\n"):
            if not ln.strip():
                continue
            if ln.startswith("  ") and cur:
                k, _, v = ln.strip().partition(":")
                fm[cur][k.strip()] = v.strip().strip('"')
                continue
            k, _, v = ln.partition(":")
            k, v = k.strip(), v.strip()
            if v:
                fm[k] = v.strip('"')
                cur = None
            else:
                fm[k], cur = {}, k
        return fm

    def test_size_and_frontmatter(self):
        self.assertLessEqual(len(self.text.encode("utf-8")), 12 * 1024)
        fm = self.frontmatter()
        self.assertTrue(set(fm) <= {"name", "description", "license", "compatibility", "metadata", "allowed-tools"})
        self.assertEqual(fm["name"], "ultimate-brainstorm")
        self.assertEqual(fm["name"], os.path.basename(_SK))
        self.assertLessEqual(len(fm["description"]), 1024)
        self.assertLessEqual(len(fm["compatibility"]), 500)
        self.assertEqual(fm["license"], "MIT")
        with open(os.path.join(_KIT, "VERSION"), encoding="utf-8") as f:
            self.assertEqual(fm["metadata"]["version"], f.read().strip())

    def test_driver_content(self):
        for needle in ("${CLAUDE_SKILL_DIR}", "${KIMI_SKILL_DIR}", "## Setup", "## Commands", "## The loop",
                       "## Hosts", "## Hard rules", '"answer_template"', '"answer_cmd"', '"task.done_cmd"',
                       "KIT/templates/host/HOST-BATCH.md", "| Claude Code | /ultimate-brainstorm | 540 |",
                       "| Codex | $ultimate-brainstorm | 100 |", "| Kimi Code | /skill:ultimate-brainstorm | 270 |",
                       "| ZCode, other | $ultimate-brainstorm | 50 |", "never a fork",
                       "brainstorm/.kickoff.txt", "--text-file"):
            self.assertIn(needle, self.text)
        # HOST-BATCH.md is the one source of the sub-agent task text (SKILL.md only points to it)
        self.assertNotIn("Read <prompt_file> and follow it", self.text)
        # the Start line writes the kickoff file, and hard rule 7 allows exactly that one write outside the run folder
        self.assertIn("to the file brainstorm/.kickoff.txt", self.text)
        self.assertIn("UB init --host HOST --text-file brainstorm/.kickoff.txt", self.text)
        rule7 = re.search(r"^7\. (.+?)(?=^\d+\. )", self.text, re.M | re.S).group(1)
        self.assertIn("(and brainstorm/.kickoff.txt for the Start command)", " ".join(rule7.split()))
        rules = re.findall(r"^(\d+)\. ", self.text[self.text.index("## Hard rules"):], re.M)
        self.assertGreaterEqual(len(rules), 11)
        for phrase in ("Human first", "Framing asks questions", "Never paste pool/", "Never call anything \"novel\"",
                       "The human decides", "Never commit", "never switch model families yourself",
                       "Privacy answers are binding", "never in a", "follow only that file"):
            self.assertIn(phrase, self.text)


