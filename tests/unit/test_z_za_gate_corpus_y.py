def matches(intent, got):
    """The reading matches one alternative of the intent; `readback [<reading>]` matches only a read-back."""
    for alt in intent.split(" | "):
        parts = alt.split()
        if parts[0] == "readback":
            if got.get("how") == "rb" and (len(parts) == 1 or q.matches(" ".join(parts[1:]), got)):
                return True
        elif q.matches(alt, got):
            return True
    return False


