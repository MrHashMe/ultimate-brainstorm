class Floods(unittest.TestCase):
    """The reader stays linear: a 20000-character reply is read, and checked for a documented form, in under 3 s."""

    def test_linear(self):
        n = 20000
        floods = (
            ("G11", "B" + "." * n, {"choice": "B"}), ("G11", "please " * (n // 7) + "B", {"choice": "B"}),
            ("G11", "B " + "ty." * (n // 3), {"choice": "B"}), ("G11", "go with" + " " * n + "B", {"choice": "B"}),
            ("G11", "B + steal A: x" + " " * n + "y", {"choice": "B"}),
            ("G13", "changes: " + "will send " * (n // 10), {"action": "changes"}),
            ("G4", "rescue I-012: " + "only if " * (n // 8), {"rescue": [{"id": "I-012", "reason": "x"}]}),
            ("G9", "passed, " + "14 of 20 " * (n // 9), {"result": "PASSED"}),
            ("G9", "passed" + " Ab" * (n // 3), {"result": "PASSED"}),
            ("G5", "- [ ] kill I-003\n" * (n // 17), {}), ("G5", "- [x] kill I-003\n" * (n // 17), {}),
            ("G13", "no need " * (n // 8) + "switch", {}), ("G12", "reject 3, rest ok " * (n // 18), {}),
            ("G2c", "prepone " * (n // 8), {}), ("G1", "I don't not want " * (n // 17), {}),
            ("G0", "topic: " + "never mind " * (n // 11) + "\ngo", None),
            ("G0", "\nlooking forward to x" * (n // 20), None), ("G0", "internet " * (n // 9), None),
            ("GB", "raise to 300 but after " * (n // 23), {}))
        for gid, text, ans in floods:
            t0 = time.perf_counter()
            gates.parse_reply(gid, text, None, [])
            if ans is None:
                gates.parse_kickoff(text, [])
            else:
                gates.canonical(None, gid, dict(ans, reply=text))
            self.assertLess(time.perf_counter() - t0, 10.0, (gid, text[:24]))


