class GateCorpusS(tl.EngineTestCase):
    variant = "product"

    def make_ctx(self, **kw):  # the Q fixtures on the row's variant
        kw.setdefault("variant", self.variant)
        return tl.EngineTestCase.make_ctx(self, **kw)

    def read(self, gate, reply, n, opts):
        provided = reply if isinstance(reply, dict) else {"reply": reply}
        if gate == "G0v1":
            return q.read_v1(self, "2026-09-28-v%d" % n, provided)
        self.variant = opts.get("variant", "product")
        for d in opts.get("dirs") or []:
            os.makedirs(os.path.join(self.project, d), exist_ok=True)
        gid = "G0" if gate == "G0k" else gate
        ctx = q.GateCorpusQ.build(self, gate, n)
        ans, _notes, errs = gates.prepare_answer(ctx, gid, provided)
        if errs:
            return {"r": "ask", "why": errs[0]}
        with mock.patch.object(gates.registry, "render_shortlist", lambda *a, **k: None):
            effects = gates.apply(ctx, gid, ans) if gate not in ("G9", "G13") else []
        return outcome(gate, ctx, ans, effects)

    def check(self, gate):
        with mock.patch("os.fsync", lambda fd: None):  # a run per row, in a temp dir: no need to reach the disk
            self._check(gate)

    def _check(self, gate):
        for n, row in enumerate(ROWS[gate]):
            reply, intent, opts = row[0], row[1], row[2] if len(row) > 2 else {}
            made = [p for p in set(os.path.join(self.project, d.split("/")[0]) for d in opts.get("dirs") or [])
                    if not os.path.exists(p)]  # the project folders of this row only
            with self.subTest(gate=gate, reply=reply, opts=opts):
                try:
                    got = self.read(gate, reply, n, opts)
                finally:
                    for p in made:
                        shutil.rmtree(p, True)
                if (gate, _key(reply, opts)) in ASKED:
                    self.assertEqual(got["r"], "ask", "pinned as asked again, got %r" % (got,))
                else:
                    self.assertTrue(q.matches(intent, got), "want %s, got %r" % (intent, got))

    def test_asked_rows_are_rows(self):
        keys = set((g, _key(r[0], r[2] if len(r) > 2 else None)) for g in ROWS for r in ROWS[g])
        self.assertEqual(ASKED - keys, frozenset())


def _add(gate):
    setattr(GateCorpusS, "test_%s" % gate.lower(), lambda self: self.check(gate))


for _gate in ROWS:
    _add(_gate)


