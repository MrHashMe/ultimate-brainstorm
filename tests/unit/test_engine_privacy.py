CODE_FACTS = """## A. FACTS
- src/app.py handles shift swaps (src/app.py:10)
```python
def swap(a, b):
    return b, a
```
    indented_code = 1
- more facts

## A2. DOMAIN TERMS (today's system)
- **Shift**: a work period.
- **Swap** [proposed]: an exchange of two shifts.
"""


class CodeStripTests(tl.EngineTestCase):
    def test_strip_code_keeps_paths(self):
        out = pv.strip_code(CODE_FACTS)
        self.assertIn("src/app.py handles shift swaps (src/app.py:10)", out)
        self.assertNotIn("def swap", out)
        self.assertNotIn("indented_code", out)
        self.assertIn("[code omitted: privacy code = no]", out)

    def test_filter_facts_for_other_vendor(self):
        ctx = self.make_ctx(variant="software")
        self.assertTrue(pv.needs_code_strip(ctx.state, "gpt"))
        self.assertFalse(pv.needs_code_strip(ctx.state, "claude"))
        out = pv.filter_facts(CODE_FACTS, ctx.state, "gpt")
        self.assertNotIn("def swap", out)
        self.assertNotIn("**Shift**", out)
        self.assertIn("**Swap** [proposed]", out)
        self.assertEqual(pv.filter_facts(CODE_FACTS, ctx.state, "claude"), CODE_FACTS)
        ctx.state["privacy"]["code"] = True
        self.assertFalse(pv.needs_code_strip(ctx.state, "gpt"))

    def test_facts_placeholder_is_filtered_per_family(self):
        ctx = self.make_ctx(variant="software")
        ctx.write("02_CONTEXT.md", CODE_FACTS + "\n## B. LANDSCAPE\n- x\n## C. SEARCH BOUNDARY\n- y\n")
        gpt = registry.PLACEHOLDERS["FACTS"](ctx, {"family": "gpt"})
        claude = registry.PLACEHOLDERS["FACTS"](ctx, {"family": "claude"})
        self.assertNotIn("def swap", gpt)
        self.assertIn("def swap", claude)

    def test_repo_cwd_is_never_used_for_other_vendors(self):
        ctx = self.make_ctx(variant="software")
        spec = {"id": "x", "template": "PING", "family": "gpt", "tools": "read+web", "cwd": "repo",
                "repo_root": self.project, "out": "logs/x.txt", "contract": {"type": "text"}}
        job = builders.make_job(ctx, {"id": "3.1"}, spec, write=False)
        self.assertEqual(job["cwd"], "empty")
        self.assertIsNone(job["repo_root"])
        self.assertEqual(job["tools"], "web")
        self.assertTrue(job["privacy"]["code_ok"])
        spec["family"] = "claude"
        job = builders.make_job(ctx, {"id": "3.1"}, spec, write=False)
        self.assertEqual(job["cwd"], "repo")


class JobStampTests(tl.EngineTestCase):
    def test_privacy_stamp(self):
        ctx = self.make_ctx(privacy={"web": False})
        stamp = pv.job_privacy(ctx.state, "gpt", "web", "empty")
        self.assertFalse(stamp["web_ok"])
        self.assertTrue(stamp["vendor_ok"])
        ctx.state["privacy"]["allowed_vendors"] = ["anthropic"]
        self.assertFalse(pv.job_privacy(ctx.state, "gpt", "none", "empty")["vendor_ok"])
        self.assertFalse(pv.job_privacy(ctx.state, "gpt", "none", "repo")["code_ok"])

    def test_web_tools_removed_when_privacy_says_no(self):
        ctx = self.make_ctx(privacy={"web": False})
        spec = {"id": "x", "template": "PING", "family": "claude", "tools": "read+web", "out": "logs/x.txt",
                "contract": {"type": "text"}}
        job = builders.make_job(ctx, {"id": "3.1"}, spec, write=False)
        self.assertEqual(job["tools"], "read")
        self.assertIn("NOT allowed", registry.PLACEHOLDERS["PRIVACY_NOTE"](ctx, {"template": "CHECK",
                                                                                  "tools": "none"}))


