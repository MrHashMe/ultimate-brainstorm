SEEDS = """# Human seeds

## Problem
Night nurses cannot swap shifts easily.

## Primary idea (to pressure-test)
- A shared points ledger for swapping night shifts

## Ideas
- Nurses trade shifts through a points ledger that the ward can see
- short one

## Obvious
- A marketplace app for shifts between hospitals

## Off-limits
- Anything touching payroll systems directly
"""


class SeedLeakTests(tl.EngineTestCase):
    def setUp(self):
        tl.EngineTestCase.setUp(self)
        self.ctx = self.make_ctx()
        self.ctx.write("00_HUMAN_SEEDS.md", SEEDS)

    def test_seed_lines(self):
        lines = pv.seed_lines(self.ctx.run_dir)
        self.assertIn("Nurses trade shifts through a points ledger that the ward can see", lines)
        self.assertIn("A shared points ledger for swapping night shifts", lines)
        self.assertIn("A marketplace app for shifts between hospitals", lines)
        self.assertNotIn("short one", lines)  # under 20 characters
        self.assertFalse(any("payroll" in x for x in lines))  # Off-limits is not sealed
        self.assertFalse(any("swap shifts easily" in x for x in lines))  # nor is the Problem

    def test_leak_is_refused_with_the_rule_name(self):
        prompt = "BRIEF\nsomething\n  nurses trade shifts   through a points ledger that the ward can see\n"
        with self.assertRaises(pv.PolicyBlock) as cm:
            pv.check_seed_leak(prompt, self.ctx.run_dir, "4.2-S3")
        self.assertEqual(cm.exception.rule, "seed_leak_check")
        pv.check_seed_leak("nothing sealed here", self.ctx.run_dir, "x")

    def test_topic_and_proposal_idea_are_allowed(self):
        prompt = "Topic: A shared points ledger for swapping night shifts"
        pv.check_seed_leak(prompt, self.ctx.run_dir, "x", allow=["A shared points ledger for swapping night shifts"])
        with self.assertRaises(pv.PolicyBlock):
            pv.check_seed_leak(prompt, self.ctx.run_dir, "x")

    def test_dispatch_returns_a_blocked_card_naming_the_rule(self):
        ctx = self.ctx
        # the frame (hence the generator BRIEF) carries a sealed seed line
        ctx.write("01_FRAME.md", "# FRAME: x\n## Job statement\nx\n## Problem\nNurses trade shifts through a points "
                                 "ledger that the ward can see\n## Axes\n- A: a | b\n")
        steps = [{"id": "4.2", "stage": 4, "title": "Diverge", "type": "DISPATCH", "fanout": "strategies",
                  "job": {"kind": "generator"}, "min_ok": "3/5"}]
        card = pipeline.advance(ctx, steps, 0)
        self.assertEqual(card["type"], "BLOCKED")
        self.assertIn("seed_leak_check", card["say"])
        self.assertEqual(ctx.deps.batch.launched, [])

    def test_the_curator_may_see_seeds(self):
        ctx = self.ctx
        ctx.write("pool/S2_vs.md", "### S2-01 Some idea title here\n- Pitch: p\n- Mechanism: m\n- Fails if: f\n")
        items = registry.FANOUTS["curator"](ctx, {"id": "5.1"})
        job = builders.make_job(ctx, {"id": "5.1"}, items[0], write=False)
        prompt = ctx.read(job["prompt_file"]) if ctx.exists(job["prompt_file"]) else builders.fill(
            ctx, builders.template_text("CURATOR"), {"template": "CURATOR", "family": "claude",
                                                      "contract": items[0]["contract"]})
        self.assertIn("points ledger", prompt)


