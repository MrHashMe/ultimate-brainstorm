IMPORT = "# Ideas from our workshop\n\n## GPT-4 shift summaries\nA nightly summary of open swaps from the swap board.\n"


def curator_keeps(title):
    orig = stubs.respond

    def respond(job, prompt):
        text = orig(job, prompt)
        if job.get("template") in ("CURATOR", "QUICK-CURATE"):
            data = json.loads(text)
            data["ideas"][0]["title"] = title  # the curator keeps the imported idea's name
            text = json.dumps(data, indent=1)
        return text
    return respond


def curated_with(field, text):
    orig = stubs._quick_curated

    def fn(ctx):
        out = orig(ctx)
        out["ideas"][0][field] = text
        return out
    return fn


class JudgeRunTests(tl.EngineTestCase):
    """Full-auto runs on two families, driven with the stubs."""

    def run_import(self, mode):
        ctx = tl.full_auto_ctx(self, mode=mode, families=("claude", "gpt"), run_name="2026-09-27-" + mode)
        ctx.write("pool/IMPORT_workshop.md", IMPORT)  # what `ub import workshop.md` writes before curation
        with mock.patch.object(stubs, "respond", curator_keeps("GPT-4 shift summaries")):
            return tl.drive(ctx)

    def test_an_imported_heading_term_reaches_done(self):
        for mode in ("standard", "quick"):
            card = self.run_import(mode)
            self.assertEqual(card["type"], "DONE", "%s: %s" % (mode, json.dumps(card)[:600]))

    def run_quick(self, n, text):
        ctx = tl.full_auto_ctx(self, mode="quick", families=("claude", "gpt"), run_name="2026-09-27-q%d" % n)
        with mock.patch.object(stubs, "_quick_curated", curated_with("mechanism", text)):
            return tl.drive(ctx)

    def test_ordinary_curated_text_reaches_done(self):
        for n, text in enumerate(("Escalation strategy: human coordinators take over at night.",
                                  "Handwritten letters written by human volunteers, scanned each week.")):
            card = self.run_quick(n, text)
            self.assertEqual(card["type"], "DONE", "%s: %s" % (text, json.dumps(card)[:600]))

    def test_a_markdown_origin_label_blocks_the_quick_screen(self):
        for n, text in enumerate(("**Origin:** gpt. A shared swap board.", "Generated by: `claude`. A swap board.")):
            card = self.run_quick(n, text)
            self.assertEqual(card["type"], "BLOCKED", text)
            self.assertIn("(in quick/curated.json)", card.get("say") or "", text)

    def test_ordinary_architecture_wording_reaches_done(self):
        orig = stubs._arch_candidate

        def candidate(ctx):
            out = orig(ctx)
            out.update(summary="Storage strategy: S3 buckets with lifecycle rules.",
                       deployment="CloudFront in front of the origin S3 bucket.")
