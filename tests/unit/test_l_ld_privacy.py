class OriginLabelShapeTests(unittest.TestCase):
    def test_ordinary_prose_passes(self):
        for text in ORDINARY:
            pv.check_origin_labels(text, "6.2-claude", aliases=ALIASES, labels=["claude", "gpt"])

    def test_labels_are_refused_also_with_markdown(self):
        for text in LABELS:
            with self.assertRaises(pv.PolicyBlock, msg=text) as cm:
                pv.check_origin_labels(text, "6.2-claude", aliases=ALIASES, labels=["claude", "gpt"])
            self.assertEqual(cm.exception.rule, "origin_label_check")

    def test_only_this_runs_prefixes_are_label_values(self):
        pv.check_origin_labels("Backup strategy: R2.", "x", aliases=["S2-01"])
        with self.assertRaises(pv.PolicyBlock):
            pv.check_origin_labels("Backup strategy: R2.", "x")  # no run: the kit's alias shapes
        with self.assertRaises(pv.PolicyBlock):
            pv.check_origin_labels("strategy: HAlice", "x", aliases=["HAlice-01"])

    def test_the_topic_is_taken_out_across_a_line_break(self):
        topic = "essays generated by Claude"
        pv.check_origin_labels("BRIEF: essays generated\nby Claude", "x", aliases=[], allow=[topic])


